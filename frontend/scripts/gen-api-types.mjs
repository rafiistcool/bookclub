// Generates src/api/generated.ts from the server's OpenAPI document (#47).
//
//   npm run gen:api     regenerates the file
//   npm run check:api   regenerates it and fails when it differs from the committed file (CI)
//
// The document comes from `bookclub-server openapi`, run through cargo with SQLX_OFFLINE=true, so
// no database is needed (the query macros read server/.sqlx/). It stays in memory: nothing but
// generated.ts is written. openapi-typescript turns it into types: `paths` and `operations` for
// the routes, `components` for the schemas, and one exported alias per schema (`BookOut`,
// `ShelfItemOut`, …) for imports.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const FRONTEND = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = "src/api/generated.ts";
const SCHEMA_REF = "#/components/schemas/";
const METHODS = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];

const HEADER = `/**
 * Generated by \`npm run gen:api\` (scripts/gen-api-types.mjs) from the server's OpenAPI
 * document. Do not edit: CI regenerates it and fails when the committed file is stale.
 */

`;

function fail(message) {
  console.error(`gen-api-types: ${message}`);
  process.exit(1);
}

/** The server's OpenAPI document, printed by `bookclub-server openapi`. */
function serverDocument() {
  let json;
  try {
    json = execFileSync(
      "cargo",
      ["run", "--quiet", "--locked", "--manifest-path", "../server/Cargo.toml", "--", "openapi"],
      {
        cwd: FRONTEND,
        env: { ...process.env, SQLX_OFFLINE: "true" },
        encoding: "utf8",
        maxBuffer: 64 * 1024 * 1024,
        stdio: ["ignore", "pipe", "inherit"],
      },
    );
  } catch (error) {
    fail(`\`cargo run -- openapi\` failed (${error.message.split("\n")[0]})`);
  }
  return JSON.parse(json);
}

/** Adds the name of every component schema that `node` references, directly or not, to `into`. */
function collectRefs(node, schemas, into) {
  if (Array.isArray(node)) {
    for (const item of node) collectRefs(item, schemas, into);
    return;
  }
  if (node === null || typeof node !== "object") return;
  for (const [key, value] of Object.entries(node)) {
    if (key === "$ref" && typeof value === "string" && value.startsWith(SCHEMA_REF)) {
      const name = value.slice(SCHEMA_REF.length);
      if (!into.has(name)) {
        into.add(name);
        collectRefs(schemas[name], schemas, into);
      }
    } else {
      collectRefs(value, schemas, into);
    }
  }
}

/** Marks every property of `schema` and of its inline subschemas required. It stops at `$ref`s. */
function requireAllProperties(schema) {
  if (schema === null || typeof schema !== "object" || Array.isArray(schema)) return;
  if (schema.properties) {
    schema.required = Object.keys(schema.properties);
    for (const property of Object.values(schema.properties)) requireAllProperties(property);
  }
  for (const key of ["items", "additionalProperties", "not"]) requireAllProperties(schema[key]);
  for (const key of ["allOf", "anyOf", "oneOf", "prefixItems"]) {
    for (const member of schema[key] ?? []) requireAllProperties(member);
  }
}

/**
 * utoipa marks `Option<T>` fields optional, but the server sends every response field, `null`
 * when empty (endpoint-map.md: "Every response field is always present"; serde never skips one,
 * which server/tests/openapi_contract.rs checks). So every property of a schema that only
 * responses use becomes required: the types read `x: T | null`, not `x?: T | null`. A schema that a
 * request body or parameter uses, directly or nested, keeps its optional fields, because a client
 * may leave them out.
 */
function requireResponseFields(doc) {
  const schemas = doc.components?.schemas ?? {};
  const operations = Object.values(doc.paths ?? {}).flatMap((item) =>
    METHODS.filter((method) => item[method]).map((method) => item[method]),
  );

  const inRequests = new Set();
  for (const item of Object.values(doc.paths ?? {})) collectRefs(item.parameters, schemas, inRequests);
  for (const operation of operations) {
    collectRefs(operation.parameters, schemas, inRequests);
    collectRefs(operation.requestBody, schemas, inRequests);
  }

  for (const [name, schema] of Object.entries(schemas)) {
    if (!inRequests.has(name)) requireAllProperties(schema);
  }
  for (const operation of operations) {
    for (const response of Object.values(operation.responses ?? {})) {
      for (const media of Object.values(response.content ?? {})) requireAllProperties(media.schema);
    }
  }
}

/** Fails unless the regenerated file matches git's index (`git diff --exit-code`). */
function checkCommitted() {
  const git = (args, stdio = "ignore") => execFileSync("git", args, { cwd: FRONTEND, stdio });
  try {
    git(["rev-parse", "--is-inside-work-tree"]);
  } catch {
    fail("check:api needs a git checkout");
  }
  try {
    git(["ls-files", "--error-unmatch", "--", OUTPUT]);
    git(["diff", "--exit-code", "--", OUTPUT], "inherit");
  } catch {
    fail(`frontend/${OUTPUT} is out of date. Run \`npm run gen:api\` in frontend/ and commit it.`);
  }
}

const args = process.argv.slice(2);
const check = args.includes("--check");
const unknown = args.filter((arg) => arg !== "--check");
if (unknown.length > 0) fail(`unknown argument ${unknown[0]} (only --check is accepted)`);

const doc = serverDocument();
requireResponseFields(doc);
const ast = await openapiTS(doc, { rootTypes: true, rootTypesNoSchemaPrefix: true });
writeFileSync(join(FRONTEND, OUTPUT), HEADER + astToString(ast));
console.log(`gen-api-types: wrote ${OUTPUT}`);
if (check) checkCommitted();
